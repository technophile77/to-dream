"""``to-dream schedule``: install, remove or inspect the nightly ``run --project all`` job.

Windows uses Task Scheduler (``schtasks`` plus StartWhenAvailable), macOS a launchd
LaunchAgent with StartCalendarInterval, Linux a systemd user timer with ``Persistent=true``
(or crontab when ``systemctl --user`` is unavailable). The job calls a small generated
wrapper in ``$TO_DREAM_HOME/runtime/`` that exports ``TO_DREAM_HOME``, checks for updates and
appends to ``$TO_DREAM_HOME/logs/<date>.log``. Builders are pure; every external command goes
through an injectable runner so tests never touch a real scheduler.
"""
from __future__ import annotations

import json
import os
import plistlib
import re
import shlex
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Optional

from . import config, runtime, state

DEFAULT_TIME = "03:30"
TASK_NAME = "to-dream-nightly"          # Windows scheduled task
LAUNCHD_LABEL = "io.github.technophile77.to-dream"
SYSTEMD_UNIT = "to-dream"                # to-dream.service / to-dream.timer
CRON_MARKER = "# to-dream nightly"
STARTWHENAVAILABLE_SCRIPT = (
    "Set-ScheduledTask -TaskName '%s' -Settings (New-ScheduledTaskSettingsSet "
    "-StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries) | Out-Null" % TASK_NAME)

Runner = Callable[..., "subprocess.CompletedProcess[str]"]


def run_cmd(argv: list[str], input: Optional[str] = None) -> "subprocess.CompletedProcess[str]":
    """Run ``argv`` capturing text output; a missing executable yields returncode 127."""
    try:
        return subprocess.run(argv, input=input, capture_output=True, text=True,
                              encoding="utf-8", errors="replace", timeout=120)
    except (FileNotFoundError, subprocess.TimeoutExpired) as exc:
        return subprocess.CompletedProcess(argv, 127, "", str(exc))


@dataclass
class Context:
    """Everything platform-specific the scheduler code needs, so tests can substitute it."""
    platform: str = field(default_factory=lambda: sys.platform)
    home: Path = field(default_factory=lambda: Path(state.home()))   # $TO_DREAM_HOME
    user_home: Path = field(default_factory=Path.home)
    python: str = field(default_factory=lambda: sys.executable)
    path_dirs: list[str] = field(default_factory=list)               # dirs of claude/git to put on PATH
    uid: int = field(default_factory=lambda: os.getuid() if hasattr(os, "getuid") else 0)
    runner: Runner = run_cmd

    @property
    def runtime(self) -> Path:
        return self.home / runtime.RUNTIME_DIRNAME

    @property
    def is_windows(self) -> bool:
        return self.platform.startswith("win")

    @property
    def is_macos(self) -> bool:
        return self.platform == "darwin"

    @property
    def wrapper(self) -> Path:
        return self.runtime / ("run-nightly.cmd" if self.is_windows else "run-nightly.sh")

    @property
    def launchd_plist(self) -> Path:
        return self.user_home / "Library" / "LaunchAgents" / (LAUNCHD_LABEL + ".plist")

    @property
    def systemd_dir(self) -> Path:
        base = os.environ.get("XDG_CONFIG_HOME")
        return (Path(base) if base else self.user_home / ".config") / "systemd" / "user"


def default_path_dirs() -> list[str]:
    """Directories holding ``claude`` and ``git``, so the job finds them under a minimal PATH."""
    dirs: list[str] = []
    for tool in ("claude", "git"):
        found = shutil.which(tool)
        if found and str(Path(found).parent) not in dirs:
            dirs.append(str(Path(found).parent))
    return dirs


# ---------------------------------------------------------------- pure builders

def parse_time(text: str) -> tuple[int, int]:
    """Parse ``HH:MM`` (24 h) into ``(hour, minute)``.

    Raises:
        ValueError: if ``text`` is not a valid 24-hour time.

    Example:
        >>> parse_time("03:30")
        (3, 30)
    """
    match = re.fullmatch(r"(\d{1,2}):(\d{2})", str(text).strip())
    if not match or int(match.group(1)) > 23 or int(match.group(2)) > 59:
        raise ValueError("time must be HH:MM (24 h), got %r" % (text,))
    return int(match.group(1)), int(match.group(2))


def build_sh_wrapper(ctx: Context) -> str:
    """Return the POSIX wrapper script: export env, log to ``logs/<date>.log``, check update, run."""
    script = ctx.runtime / "scripts" / "to_dream.py"
    lines = [
        "#!/bin/sh",
        "# Generated by `to-dream schedule install`; regenerated on every install.",
        "TO_DREAM_HOME=%s" % shlex.quote(str(ctx.home)),
        "export TO_DREAM_HOME",
        "PYTHONUTF8=1",
        "export PYTHONUTF8",
    ]
    if ctx.path_dirs:
        lines.append("PATH=%s:\"$PATH\"" % ":".join(shlex.quote(d) for d in ctx.path_dirs))
        lines.append("export PATH")
    lines += [
        'mkdir -p "$TO_DREAM_HOME/logs"',
        'LOG="$TO_DREAM_HOME/logs/$(date +%Y-%m-%d).log"',
        'echo "== to-dream nightly run $(date) ==" >> "$LOG"',
        "%s %s check-update --force >> \"$LOG\" 2>&1" % (shlex.quote(ctx.python), shlex.quote(str(script))),
        "%s %s run --project all >> \"$LOG\" 2>&1" % (shlex.quote(ctx.python), shlex.quote(str(script))),
        "STATUS=$?",
        'echo "== finished $(date) (exit $STATUS) ==" >> "$LOG"',
        'exit "$STATUS"',
        "",
    ]
    return "\n".join(lines)


def build_cmd_wrapper(ctx: Context) -> str:
    """Return the Windows ``.cmd`` wrapper (same steps as the POSIX one; CRLF line endings)."""
    script = ctx.runtime / "scripts" / "to_dream.py"
    py = '"%s"' % ctx.python
    lines = [
        "@echo off",
        "rem Generated by `to-dream schedule install`; regenerated on every install.",
        'set "TO_DREAM_HOME=%s"' % ctx.home,
        "set PYTHONUTF8=1",
    ]
    if ctx.path_dirs:
        lines.append('set "PATH=%s;%%PATH%%"' % ";".join(ctx.path_dirs))
    lines += [
        'if not exist "%TO_DREAM_HOME%\\logs" mkdir "%TO_DREAM_HOME%\\logs"',
        # PowerShell supplies the date: %DATE% is locale-dependent, and quoting a python.exe path
        # inside for /f trips cmd's quote stripping
        "for /f %%i in ('powershell -NoProfile -Command \"Get-Date -Format yyyy-MM-dd\"') do set \"TD_DAY=%%i\"",
        'set "LOG=%TO_DREAM_HOME%\\logs\\%TD_DAY%.log"',
        'echo == to-dream nightly run %DATE% %TIME% == >> "%LOG%"',
        py + ' "' + str(script) + '" check-update --force >> "%LOG%" 2>&1',
        py + ' "' + str(script) + '" run --project all >> "%LOG%" 2>&1',
        'set "RC=%ERRORLEVEL%"',
        'echo == finished %DATE% %TIME% (exit %RC%) == >> "%LOG%"',
        "exit /b %RC%",
        "",
    ]
    return "\r\n".join(lines)


def build_plist(ctx: Context, hour: int, minute: int) -> bytes:
    """Return the launchd LaunchAgent plist (XML) that runs the wrapper daily at ``hour:minute``."""
    return plistlib.dumps({
        "Label": LAUNCHD_LABEL,
        "ProgramArguments": ["/bin/sh", str(ctx.wrapper)],
        "StartCalendarInterval": {"Hour": hour, "Minute": minute},
        "RunAtLoad": False,
    })


def _systemd_quote(value: str) -> str:
    return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')


def build_systemd_units(ctx: Context, hour: int, minute: int) -> dict[str, str]:
    """Return ``{filename: content}`` for the user service and the persistent daily timer."""
    service = (
        "[Unit]\nDescription=to-dream nightly memory consolidation\n\n"
        "[Service]\nType=oneshot\nExecStart=/bin/sh %s\n" % _systemd_quote(str(ctx.wrapper)))
    timer = (
        "[Unit]\nDescription=Run to-dream nightly\n\n"
        "[Timer]\nOnCalendar=*-*-* %02d:%02d:00\nPersistent=true\n\n"
        "[Install]\nWantedBy=timers.target\n" % (hour, minute))
    return {SYSTEMD_UNIT + ".service": service, SYSTEMD_UNIT + ".timer": timer}


def build_cron_line(ctx: Context, hour: int, minute: int) -> str:
    """Return the crontab entry (tagged with a marker comment so it can be found again)."""
    return "%d %d * * * /bin/sh %s %s" % (minute, hour, shlex.quote(str(ctx.wrapper)), CRON_MARKER)


def merge_crontab(existing: str, line: Optional[str]) -> str:
    """Return ``existing`` without any to-dream entry, plus ``line`` (if given) appended."""
    kept = [ln for ln in existing.splitlines() if CRON_MARKER not in ln]
    if line:
        kept.append(line)
    return "\n".join(kept) + "\n" if kept else ""


def schtasks_create_argv(ctx: Context, hour: int, minute: int) -> list[str]:
    """Return the ``schtasks /Create`` argv for a daily task at ``hour:minute`` running the wrapper."""
    return ["schtasks", "/Create", "/TN", TASK_NAME, "/TR", '"%s"' % ctx.wrapper,
            "/SC", "DAILY", "/ST", "%02d:%02d" % (hour, minute), "/F"]


def powershell_argv() -> list[str]:
    """Return the argv enabling StartWhenAvailable (catch up a missed run) on the task."""
    return ["powershell", "-NoProfile", "-Command", STARTWHENAVAILABLE_SCRIPT]


# ---------------------------------------------------------------- actions

def _write_text(path: Path, text: str, newline: str = "\n") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline=newline)


def _systemd_available(ctx: Context) -> bool:
    return ctx.runner(["systemctl", "--user", "show-environment"]).returncode == 0


def _fail(result, what: str) -> str:
    return "%s failed (exit %s): %s" % (what, result.returncode, (result.stderr or result.stdout or "").strip())


def install(ctx: Context, time_text: str) -> tuple[int, list[str]]:
    """Install the nightly job at ``time_text`` (HH:MM); returns ``(exit_code, messages)``.

    Syncs the runtime copy first, writes the wrapper, then registers it with the platform
    scheduler. Raises nothing: failures come back as a non-zero code and a message.

    Example:
        >>> install(Context(), "03:30")[0]
        0
    """
    try:
        hour, minute = parse_time(time_text)
    except ValueError as exc:
        return 2, [str(exc)]
    try:
        runtime.sync(home=ctx.home)
        if ctx.is_windows:
            _write_text(ctx.wrapper, build_cmd_wrapper(ctx), newline="")
        else:
            _write_text(ctx.wrapper, build_sh_wrapper(ctx))
            ctx.wrapper.chmod(0o755)
    except OSError as exc:
        return 1, ["could not write the wrapper script: %s" % exc]

    if ctx.is_windows:
        return _install_windows(ctx, hour, minute)
    if ctx.is_macos:
        return _install_launchd(ctx, hour, minute)
    return _install_linux(ctx, hour, minute)


def _install_windows(ctx: Context, hour: int, minute: int) -> tuple[int, list[str]]:
    created = ctx.runner(schtasks_create_argv(ctx, hour, minute))
    if created.returncode != 0:
        return 1, [_fail(created, "schtasks /Create")]
    messages = ["Scheduled task '%s' created: daily at %02d:%02d." % (TASK_NAME, hour, minute)]
    catchup = ctx.runner(powershell_argv())
    if catchup.returncode != 0:
        messages.append("warning: could not enable catch-up after a missed start. " + _fail(catchup, "powershell"))
    else:
        messages.append("Catch-up after a missed start is enabled (StartWhenAvailable).")
    messages.append("The task runs only while you are logged on. Log: %s" % (ctx.home / "logs"))
    return 0, messages


def _install_launchd(ctx: Context, hour: int, minute: int) -> tuple[int, list[str]]:
    plist = ctx.launchd_plist
    _write_text(plist, build_plist(ctx, hour, minute).decode("utf-8"))
    domain = "gui/%d" % ctx.uid
    ctx.runner(["launchctl", "bootout", domain, str(plist)])  # ignore: it may not be loaded yet
    loaded = ctx.runner(["launchctl", "bootstrap", domain, str(plist)])
    if loaded.returncode != 0:
        return 1, [_fail(loaded, "launchctl bootstrap")]
    return 0, ["LaunchAgent %s installed: daily at %02d:%02d (a missed start runs on wake)." % (LAUNCHD_LABEL, hour, minute),
               "Log: %s" % (ctx.home / "logs")]


def _install_linux(ctx: Context, hour: int, minute: int) -> tuple[int, list[str]]:
    if _systemd_available(ctx):
        for name, content in build_systemd_units(ctx, hour, minute).items():
            _write_text(ctx.systemd_dir / name, content)
        ctx.runner(["systemctl", "--user", "daemon-reload"])
        enabled = ctx.runner(["systemctl", "--user", "enable", "--now", SYSTEMD_UNIT + ".timer"])
        if enabled.returncode != 0:
            return 1, [_fail(enabled, "systemctl enable")]
        _cron_apply(ctx, None)  # drop an older cron fallback so the job doesn't run twice
        return 0, ["systemd user timer %s.timer enabled: daily at %02d:%02d, Persistent=true (catches up after downtime)." % (
            SYSTEMD_UNIT, hour, minute),
            "To run while logged out, enable lingering: loginctl enable-linger $USER",
            "Log: %s" % (ctx.home / "logs")]
    code, messages = _cron_apply(ctx, build_cron_line(ctx, hour, minute))
    if code == 0:
        messages = ["systemd user manager unavailable; installed a crontab entry: daily at %02d:%02d." % (hour, minute),
                    "cron does not catch up after a missed start.", "Log: %s" % (ctx.home / "logs")]
    return code, messages


def _cron_apply(ctx: Context, line: Optional[str]) -> tuple[int, list[str]]:
    """Replace the to-dream crontab entry with ``line`` (None removes it)."""
    listing = ctx.runner(["crontab", "-l"])
    if listing.returncode == 127:
        return (0, []) if line is None else (1, ["neither systemd --user nor crontab is available"])
    existing = listing.stdout if listing.returncode == 0 else ""  # "no crontab for user" exits 1
    if line is None and CRON_MARKER not in existing:
        return 0, []
    written = ctx.runner(["crontab", "-"], input=merge_crontab(existing, line))
    if written.returncode != 0:
        return 1, [_fail(written, "crontab")]
    return 0, []


def remove(ctx: Context) -> tuple[int, list[str]]:
    """Remove the nightly job (and its unit files); safe to call when nothing is installed."""
    messages: list[str] = []
    code = 0
    if ctx.is_windows:
        deleted = ctx.runner(["schtasks", "/Delete", "/TN", TASK_NAME, "/F"])
        if deleted.returncode == 0:
            messages.append("Removed scheduled task '%s'." % TASK_NAME)
        elif ctx.runner(["schtasks", "/Query", "/TN", TASK_NAME]).returncode == 0:
            code, messages = 1, [_fail(deleted, "schtasks /Delete")]
    elif ctx.is_macos:
        plist = ctx.launchd_plist
        if plist.exists():
            ctx.runner(["launchctl", "bootout", "gui/%d" % ctx.uid, str(plist)])
            plist.unlink()
            messages.append("Removed LaunchAgent %s." % LAUNCHD_LABEL)
    else:
        unit_files = [ctx.systemd_dir / (SYSTEMD_UNIT + ext) for ext in (".timer", ".service")]
        if any(p.exists() for p in unit_files):
            ctx.runner(["systemctl", "--user", "disable", "--now", SYSTEMD_UNIT + ".timer"])
            for path in unit_files:
                path.unlink(missing_ok=True)
            ctx.runner(["systemctl", "--user", "daemon-reload"])
            messages.append("Removed systemd user timer %s.timer." % SYSTEMD_UNIT)
        cron_code, cron_messages = _cron_apply(ctx, None)
        code = max(code, cron_code)
        messages += cron_messages
    try:
        ctx.wrapper.unlink(missing_ok=True)
    except OSError:
        pass
    return code, messages or ["No to-dream schedule was installed."]


def status(ctx: Context) -> dict:
    """Describe the installed job: ``{installed, mechanism, time, catch_up, detail}``.

    ``time`` is 'HH:MM' when it could be read back, else None. Never raises.
    """
    try:
        if ctx.is_windows:
            return _status_windows(ctx)
        if ctx.is_macos:
            return _status_launchd(ctx)
        return _status_linux(ctx)
    except Exception as exc:  # status must never break doctor
        return _status_dict(False, None, None, None, "status check failed: %s" % exc)


def _status_dict(installed: bool, mechanism: Optional[str], time: Optional[str],
                 catch_up: Optional[bool], detail: str) -> dict:
    return {"installed": installed, "mechanism": mechanism, "time": time, "catch_up": catch_up, "detail": detail}


def _status_windows(ctx: Context) -> dict:
    result = ctx.runner(["schtasks", "/Query", "/TN", TASK_NAME, "/XML"])
    if result.returncode != 0:
        return _status_dict(False, "task-scheduler", None, None, "not installed")
    text = re.sub(r"^<\?xml[^>]*\?>", "", result.stdout.strip())
    text = re.sub(r'\sxmlns="[^"]+"', "", text, count=1)
    root = ET.fromstring(text)
    start = root.findtext(".//StartBoundary") or ""
    match = re.search(r"T(\d{2}:\d{2})", start)
    catch_up = (root.findtext(".//StartWhenAvailable") or "").strip().lower() == "true"
    return _status_dict(True, "task-scheduler", match.group(1) if match else None, catch_up,
                        "scheduled task '%s'" % TASK_NAME)


def _status_launchd(ctx: Context) -> dict:
    plist = ctx.launchd_plist
    if not plist.exists():
        return _status_dict(False, "launchd", None, None, "not installed")
    data = plistlib.loads(plist.read_bytes())
    when = data.get("StartCalendarInterval", {})
    time = "%02d:%02d" % (when.get("Hour", 0), when.get("Minute", 0)) if when else None
    loaded = ctx.runner(["launchctl", "print", "gui/%d/%s" % (ctx.uid, LAUNCHD_LABEL)]).returncode == 0
    return _status_dict(True, "launchd", time, True,
                        "LaunchAgent %s (%s)" % (LAUNCHD_LABEL, "loaded" if loaded else "not loaded: run schedule install"))


def _status_linux(ctx: Context) -> dict:
    timer = ctx.systemd_dir / (SYSTEMD_UNIT + ".timer")
    if timer.exists():
        match = re.search(r"OnCalendar=\S+ (\d{2}:\d{2})", timer.read_text(encoding="utf-8"))
        active = ctx.runner(["systemctl", "--user", "is-enabled", SYSTEMD_UNIT + ".timer"]).returncode == 0
        return _status_dict(True, "systemd", match.group(1) if match else None, True,
                            "systemd user timer (%s)" % ("enabled" if active else "installed but not enabled"))
    listing = ctx.runner(["crontab", "-l"])
    for ln in (listing.stdout.splitlines() if listing.returncode == 0 else []):
        if CRON_MARKER in ln:
            fields = ln.split()
            time = "%02d:%02d" % (int(fields[1]), int(fields[0]))
            return _status_dict(True, "cron", time, False, "crontab entry (no catch-up after a missed start)")
    return _status_dict(False, None, None, None, "not installed")


# ---------------------------------------------------------------- CLI

def _handle(args) -> int:
    ctx = Context(path_dirs=default_path_dirs())
    action = args.schedule_action
    if action == "install":
        time_text = args.time or _configured_time()
        code, messages = install(ctx, time_text)
    elif action == "remove":
        code, messages = remove(ctx)
    else:
        info = status(ctx)
        if args.json:
            print(json.dumps(info, indent=2))
        else:
            print(info["detail"] + (" at %s" % info["time"] if info["time"] else ""))
        return 0
    print("\n".join(messages), file=sys.stderr if code else sys.stdout)
    return code


def _configured_time() -> str:
    try:
        value = config.get("schedule_time")
    except Exception:
        value = None
    return value if isinstance(value, str) and value else DEFAULT_TIME


def add_parser(subparsers) -> None:
    """Register the ``schedule`` subcommand with ``install``, ``remove`` and ``status``."""
    parser = subparsers.add_parser("schedule", help="install, remove or show the nightly run")
    actions = parser.add_subparsers(dest="schedule_action", required=True)
    install_p = actions.add_parser("install", help="install the nightly job (runs sync-runtime first)")
    install_p.add_argument("--time", metavar="HH:MM", help="local time (default: config schedule_time, else 03:30)")
    actions.add_parser("remove", help="remove the nightly job")
    status_p = actions.add_parser("status", help="show whether the job is installed")
    status_p.add_argument("--json", action="store_true", help="machine-readable output")
    parser.set_defaults(func=_handle)
